/* 图片地址按需取尺寸（Unsplash 支持 w= 参数） */
function sizedImg(url, w){
  return /[?&]w=\d+/.test(url) ? url.replace(/([?&]w=)\d+/, "$1"+w) : url;
}
function escAttr(str){
  return String(str == null ? "" : str).replace(/&/g,"&amp;").replace(/"/g,"&quot;").replace(/</g,"&lt;").replace(/>/g,"&gt;");
}
/* AI 返回的文本一律转义后再插入 innerHTML */
function escHtml(str){ return escAttr(str); }
/* 卡片顶部视觉：有实拍图就用第一张铺满，加载失败或没有图则回退到 Emoji */
function productVisual(images, emoji, alt){
  const fb = emoji || "🛍️";
  if(images && images.length){
    return `<img class="rec-img" src="${escAttr(sizedImg(images[0], 600))}" alt="${escAttr(alt)}" loading="lazy" data-fallback="${escAttr(fb)}" onerror="productImgFallback(this)">`;
  }
  return `<span class="rec-emoji">${escAttr(fb)}</span>`;
}
function productImgFallback(img){
  const span = document.createElement("span");
  span.className = "rec-emoji";
  span.textContent = img.dataset.fallback || "🛍️";
  img.replaceWith(span);
}

