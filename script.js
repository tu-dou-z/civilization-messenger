/* ================= 商路：按真实途经城市串联 ================= */
function buildCorridorRoute(){
  const stops = CITIES.map(c => ({ x: c.x, y: c.y, city: c }));
  const wps = (window.ROUTE_WAYPOINTS || []).map(w => {
    const p = GEO.project(w.lon, w.lat);
    return { x: p.x, y: p.y, city: null };
  });
  // 按经度从东到西把途经点插到对应驿站之间（驿站本身已按东→西排列）
  const nodes = [stops[0]];
  for(let i = 0; i < stops.length - 1; i++){
    const a = stops[i], b = stops[i + 1];
    const mid = wps.filter(w => w.x < a.x - 2 && w.x > b.x + 2)
      .sort((p, q) => q.x - p.x)
      .map(w => ({ x: w.x, y: w.y, city: null }));
    nodes.push(...mid, b);
  }

  // Catmull-Rom → 三次贝塞尔，保证曲线顺滑且经过每个节点
  let d = `M${nodes[0].x.toFixed(1)} ${nodes[0].y.toFixed(1)}`;
  const pts = [{ x: nodes[0].x, y: nodes[0].y, len: 0 }];
  let total = 0;
  const cityLen = [0];
  for(let i = 0; i < nodes.length - 1; i++){
    const p0 = nodes[i - 1] || nodes[i], p1 = nodes[i], p2 = nodes[i + 1], p3 = nodes[i + 2] || nodes[i + 1];
    const c1 = { x: p1.x + (p2.x - p0.x) / 6, y: p1.y + (p2.y - p0.y) / 6 };
    const c2 = { x: p2.x - (p3.x - p1.x) / 6, y: p2.y - (p3.y - p1.y) / 6 };
    d += ` C${c1.x.toFixed(1)} ${c1.y.toFixed(1)} ${c2.x.toFixed(1)} ${c2.y.toFixed(1)} ${p2.x.toFixed(1)} ${p2.y.toFixed(1)}`;
    let prev = pts[pts.length - 1];
    for(let k = 1; k <= 40; k++){
      const t = k / 40, u = 1 - t;
      const x = u * u * u * p1.x + 3 * u * u * t * c1.x + 3 * u * t * t * c2.x + t * t * t * p2.x;
      const y = u * u * u * p1.y + 3 * u * u * t * c1.y + 3 * u * t * t * c2.y + t * t * t * p2.y;
      total += Math.hypot(x - prev.x, y - prev.y);
      prev = { x, y, len: total };
      pts.push(prev);
    }
    if(nodes[i + 1].city) cityLen.push(total);
  }
  return { d, pts, cityLen, total };
}

function routePointAt(len){
  const pts = corridorRoute.pts;
  let lo = 0, hi = pts.length - 1;
  while(hi - lo > 1){
    const mid = (lo + hi) >> 1;
    if(pts[mid].len < len) lo = mid; else hi = mid;
  }
  const a = pts[lo], b = pts[hi];
  const k = b.len === a.len ? 0 : (len - a.len) / (b.len - a.len);
  return { x: a.x + (b.x - a.x) * k, y: a.y + (b.y - a.y) * k };
}

function setCaravan(len){
  caravanLen = len;
  const p = routePointAt(len);
  const car = document.getElementById("caravan");
  const prog = document.getElementById("routeProgress");
  if(car) car.setAttribute("transform", `translate(${p.x.toFixed(1)} ${p.y.toFixed(1)})`);
  if(prog) prog.style.strokeDashoffset = (1000 * (1 - len / corridorRoute.total)).toFixed(1);
}
function moveCaravan(target){
  cancelAnimationFrame(caravanRAF);
  const from = caravanLen, dist = target - from;
  if(Math.abs(dist) < 0.5){ setCaravan(target); return; }
  const dur = Math.min(1800, 600 + Math.abs(dist) * 0.9);
  const t0 = performance.now();
  const step = now => {
    const raw = Math.min(1, (now - t0) / dur);
    const k = raw < 0.5 ? 4 * raw * raw * raw : 1 - Math.pow(-2 * raw + 2, 3) / 2;
    setCaravan(from + dist * k);
    if(raw < 1) caravanRAF = requestAnimationFrame(step);
  };
  caravanRAF = requestAnimationFrame(step);
}

