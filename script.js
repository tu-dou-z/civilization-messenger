/* 平滑切换大图：先淡出，新图预加载完成后再淡入 */
function showProductImage(url, alt){
  const m = pdModal;
  if(!m || m.main.dataset.src === url) return;
  m.main.dataset.src = url;
  clearTimeout(pdSwitchTimer);
  m.main.classList.add("is-switching");
  const started = Date.now();
  const reveal = ()=>{
    if(m.main.dataset.src !== url) return;   // 期间又点了别的缩略图
    // 至少等淡出动画走完，再换图淡入
    pdSwitchTimer = setTimeout(()=>{
      m.main.src = url;
      m.main.alt = alt || "";
      requestAnimationFrame(()=> m.main.classList.remove("is-switching"));
    }, Math.max(0, 300 - (Date.now() - started)));
  };
  const pre = new Image();
  pre.onload = reveal;
  pre.onerror = reveal;
  pre.src = url;
}

