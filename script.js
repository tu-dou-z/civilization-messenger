function switchPage(page, dir){
  if(page === currentPage){ window.scrollTo({top:0,behavior:"smooth"}); return; }
  // 滑动方向决定进入动画（RTL 下自动镜像）
  const rtl = document.documentElement.getAttribute("dir") === "rtl";
  let fromClass = "";
  if(dir === "next") fromClass = rtl ? "from-left" : "from-right";
  else if(dir === "prev") fromClass = rtl ? "from-right" : "from-left";

  currentPage = page;
  document.querySelectorAll(".page").forEach(p=>{
    const active = p.dataset.page === page;
    p.classList.remove("from-left","from-right");
    if(active && fromClass) p.classList.add(fromClass);
    p.classList.toggle("active", active);
  });
  document.querySelectorAll(".tab").forEach(tb=>{
    tb.classList.toggle("active", tb.dataset.tab === page);
  });
  window.scrollTo({top:0,behavior:"smooth"});
  try{ localStorage.setItem("civmsg_page", page); }catch(e){}
}
function swipeTo(delta){
  const idx = PAGE_ORDER.indexOf(currentPage);
  const nextIdx = idx + delta;
  if(nextIdx < 0 || nextIdx >= PAGE_ORDER.length) return;
  switchPage(PAGE_ORDER[nextIdx], delta > 0 ? "next" : "prev");
}

