function addHistory(symbol, imgSrc, rec){
  STATS.scan++;
  const s = symbol ? DATA[symbol] : null;
  const recName = rec || (currentRecognition
    ? { zh: currentRecognition.name_zh, ar: currentRecognition.name_ar } : null);
  // 存 symbol（跨语言）或 AI 双语名称 + 时间戳，名称在渲染时按当前语言实时生成
  HISTORY.unshift({
    name: recName ? recName[LANG] || recName.zh : (s ? s.name[LANG] : symbol),
    nameZh: recName ? recName.zh : (s ? s.name.zh : symbol),
    nameAr: recName ? (recName.ar || recName.zh) : (s ? s.name.ar : symbol),
    symbol: symbol || null,
    rec: recName ? (currentRecognition || { name_zh: recName.zh, name_ar: recName.ar }) : null,
    img: imgSrc, ts: Date.now()
  });
  if(HISTORY.length > 8) HISTORY.pop();
  renderStats();
  renderHistory();
  saveState();
}
function timeAgo(ts){
  if(!ts) return t("justNow");
  const diff = Math.floor((Date.now() - ts) / 1000);
  if(diff < 60) return t("justNow");
  if(diff < 3600) return Math.floor(diff/60) + (LANG==="zh"?" 分钟前":" د");
  if(diff < 86400) return Math.floor(diff/3600) + (LANG==="zh"?" 小时前":" س");
  return Math.floor(diff/86400) + (LANG==="zh"?" 天前":" ي");
}
function renderHistory(){
  const box = document.getElementById("historyList");
  if(!box) return;
  if(!HISTORY.length){
    box.innerHTML = `<div class="history-empty">${t("historyEmpty")}</div>`;
    return;
  }
  box.innerHTML = HISTORY.map((h,i)=>{
    const s = h.symbol ? DATA[h.symbol] : null;
    const name = s ? s.name[LANG]
                   : (h.rec ? (LANG==="zh" ? h.rec.name_zh : (h.rec.name_ar || h.rec.name_zh))
                            : (LANG==="ar" && h.nameAr ? h.nameAr : h.name));
    return `<div class="history-item" onclick="reviewHistory(${i})" title="${t('reviewTip')}">
      <img class="h-thumb" src="${h.img}" alt="">
      <div class="h-info"><h5>${name}</h5><span>${timeAgo(h.ts)}</span></div>
      <span class="h-arrow">›</span>
    </div>`;
  }).join("");
}
